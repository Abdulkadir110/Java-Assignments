

public class kala {
        
        public static int add(int num1,int num2,int num3) {

            int sum = num1 + num2 + num3;
            return sum;
        }

        public  int substract(int num1,int num2,int num3) {

            int sub = num1 - num2 - num3;
            return sub;
        }
}
